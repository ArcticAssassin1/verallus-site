import json, shutil, os
HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.abspath(os.path.join(HERE, '..', '..'))
V = os.environ.get('MAPV', '1')
os.makedirs(f'{SITE}/public/map', exist_ok=True)
for f in os.listdir(f'{SITE}/public/map'): os.remove(f'{SITE}/public/map/{f}')
for n in ('verallus-relief', 'skyspire', 'storm'):
    shutil.copy(os.path.join(HERE, 'out', f'{n}.webp'), f'{SITE}/public/map/{n}-{V}.webp')
sh = json.load(open(os.path.join(HERE, 'out', 'shapes.json'))); ly = json.load(open(os.path.join(HERE, 'out', 'layers.json')))
lines = ['// Generated by tools/map-painter. Traced outlines of the painted map, in viewBox units.',
         '// Region keys match app/data/regions.ts. Do not edit by hand: regenerate with the painting.', '',
         f"export const MAP_IMG = {{ relief: '/map/verallus-relief-{V}.webp', skyspire: '/map/skyspire-{V}.webp', storm: '/map/storm-{V}.webp' }}", '',
         f"export const SKY_BOX = {json.dumps(ly['sky'])}", f"export const STORM_R = {ly['stormR']}", '',
         'export const MAP_SHAPES = {']
for k in ('frozen', 'dormose', 'feyvey', 'regalus', 'ashen', 'emberfell', 'oceanus', 'scar', 'echo'):
    lines.append(f"  {k}: '{sh[k]}',")
lines.append('} as const'); lines.append('')
open(f'{SITE}/app/data/mapShapes.ts', 'w').write('\n'.join(lines))
print(os.path.getsize(f'{SITE}/app/data/mapShapes.ts'))
